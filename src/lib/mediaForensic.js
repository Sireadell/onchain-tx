// Deterministic answers for media authenticity questions, tried before the
// LLM judge. Two cases are settled from facts instead of opinion:
//   1. Wikimedia Commons files: the file record (hash, size, uploader, camera
//      data, categories) is read from the Commons API and the verdict follows
//      from it, so the same question always gets the same answer.
//   2. example.com style placeholder links: no real file exists there.
// Anything else returns null and the caller falls back to the LLM judge.

const API = 'https://commons.wikimedia.org/w/api.php';
const UA = 'txlens-miner/1.0';
const TIMEOUT_MS = 6000;

const cache = new Map(); // file name -> record (successful lookups only)

export function findUrls(text) {
  return [...String(text ?? '').matchAll(/https?:\/\/[^\s"'<>)\]]+/gi)].map((m) => m[0].replace(/[.,;:!?]+$/, ''));
}

export function isPlaceholderHost(host) {
  return /(^|\.)example\.(com|org|net)$/i.test(host);
}

// File name ("Name.ext", spaces not underscores) from a Commons or
// upload.wikimedia.org link, or null.
export function commonsFileName(url) {
  let u;
  try { u = new URL(url); } catch { return null; }
  const host = u.hostname.toLowerCase();
  let name = null;
  if (host === 'upload.wikimedia.org') {
    const m = u.pathname.match(/^\/wikipedia\/commons\/(thumb\/)?[0-9a-f]\/[0-9a-f]{2}\/([^/]+)/i);
    if (m) name = m[2];
  } else if (host === 'commons.wikimedia.org' || host === 'commons.m.wikimedia.org') {
    const m = u.pathname.match(/^\/wiki\/(?:File|Image):(.+)$/i);
    if (m) name = m[1];
    else if (/^(File|Image):/i.test(u.searchParams.get('title') ?? '')) name = u.searchParams.get('title').replace(/^(File|Image):/i, '');
  }
  if (!name) return null;
  try { name = decodeURIComponent(name); } catch { /* keep raw */ }
  return name.replace(/_/g, ' ').trim() || null;
}

const strip = (v) => String(v?.value ?? v ?? '').replace(/<[^>]+>/g, ' ').replace(/&amp;/g, '&').replace(/&quot;/g, '"').replace(/\s+/g, ' ').trim();

function cameraName(make, model) {
  const mk = typeof make === 'string' ? make.trim() : '';
  const md = typeof model === 'string' ? model.trim() : '';
  if (md && mk && md.toLowerCase().startsWith(mk.toLowerCase())) return md;
  return [mk, md].filter(Boolean).join(' ') || null;
}

async function fetchRecord(name, fetchImpl) {
  if (cache.has(name)) return cache.get(name);
  const url = `${API}?action=query&redirects=1&titles=${encodeURIComponent('File:' + name)}`
    + '&prop=imageinfo|categories&iiprop=timestamp|user|size|sha1|mime|extmetadata|commonmetadata&format=json&cllimit=50';
  const ctl = new AbortController();
  const timer = setTimeout(() => ctl.abort(), TIMEOUT_MS);
  try {
    const r = await fetchImpl(url, { headers: { 'User-Agent': UA }, signal: ctl.signal });
    if (!r.ok) return undefined;
    const j = await r.json();
    const page = Object.values(j?.query?.pages ?? {})[0];
    if (!page) return undefined;
    let info;
    if (page.missing !== undefined || !page.imageinfo?.[0]) {
      info = { missing: true, name };
    } else {
      const ii = page.imageinfo[0];
      const ext = ii.extmetadata ?? {};
      const exif = Object.fromEntries((ii.commonmetadata ?? []).map((m) => [m.name, m.value]));
      info = {
        missing: false,
        name: String(page.title ?? `File:${name}`).replace(/^File:/, ''),
        sha1: ii.sha1, size: ii.size, mime: ii.mime, uploader: ii.user, uploaded: ii.timestamp,
        categories: (page.categories ?? []).map((c) => c.title.replace(/^Category:/, '')),
        camera: cameraName(exif.Make, exif.Model),
        artist: strip(ext.Artist), license: strip(ext.LicenseShortName),
        description: strip(ext.ImageDescription), credit: strip(ext.Credit),
        objectName: strip(ext.ObjectName), date: strip(ext.DateTimeOriginal),
      };
    }
    cache.set(name, info);
    return info;
  } catch {
    return undefined;
  } finally {
    clearTimeout(timer);
  }
}

const AI_CAT = /AI[- ]generated|generated by (AI|Stable|Midjourney|DALL)|Midjourney|DALL[-.\s]?E\b|Stable Diffusion (images|generated)|Images created with (AI|Stable)/i;
const AI_TEXT = /\b(AI[- ]generated|generated (by|with|using) (an? )?(AI|Stable Diffusion|Midjourney|DALL[-.\s]?E)|created (by|with|using) (an? )?(AI|Stable Diffusion|Midjourney|DALL[-.\s]?E)|Midjourney)\b/i;
const PAINTING_CAT = /Google Art Project|paintings?\b|Artworks/i;
const SOFTWARE_CAT = /Created with|source code|\bSVG\b|diagram|Computer[- ]generated|Rendered|Povray|POV-Ray|Blender|\blogos?\b|\bicons?\b|\bmaps?\b|\bcharts?\b|\bgraphs?\b|Screenshots|Illustrations|Vector graphics|Test patterns/i;

function year(info) {
  const m = `${info.description} ${info.date}`.match(/\b(1[0-9]{3}|20[0-2][0-9])\b/);
  return m ? m[1] : null;
}

// Pure decision from a Commons record: { verdict, confidence, reason, kind }.
export function classifyRecord(info) {
  const when = String(info.uploaded ?? '').slice(0, 10);
  const who = info.artist || info.uploader || 'an unnamed author';
  const cats = info.categories ?? [];

  if (cats.some((c) => AI_CAT.test(c)) || AI_TEXT.test(`${info.description} ${info.objectName}`)) {
    return { verdict: 'Fake', confidence: 0.9, kind: 'ai',
      reason: `AI-generated image, not a real photograph: the Commons record for ${info.name} files it under AI-generated content (uploaded by ${info.uploader} on ${when}).` };
  }
  if (info.camera) {
    return { verdict: 'Authentic', confidence: 0.9, kind: 'camera',
      reason: `Real photograph by ${who}, uploaded ${when}, camera ${info.camera} recorded in the file's own metadata.` };
  }
  if (cats.some((c) => PAINTING_CAT.test(c))) {
    const y = year(info);
    return { verdict: 'Authentic', confidence: 0.9, kind: 'painting',
      reason: `Authentic photographic reproduction of a real painting by ${info.artist || 'a named artist'}${y ? `, ${y}` : ''}${info.description ? ` (${info.description.slice(0, 100)})` : ''}, from the Google Art Project or museum collection on Commons.` };
  }
  const svg = /svg/i.test(info.mime ?? '');
  if (svg || cats.some((c) => SOFTWARE_CAT.test(c)) || /diagram|rendering|rendered|illustration|demonstration/i.test(`${info.description} ${info.objectName}`)) {
    return { verdict: 'Fake', confidence: 0.85, kind: 'graphic',
      reason: 'Not a real photograph: a computer-generated demonstration graphic made with software, not a camera and not AI.' };
  }
  if (/jpeg|tiff/i.test(info.mime ?? '')) {
    return { verdict: 'Authentic', confidence: 0.75, kind: 'photo',
      reason: `Photograph by ${who}, uploaded ${when}${info.credit ? `, declared as "${info.credit.slice(0, 60)}"` : ''}; no camera data is stored in the file, but nothing marks it as computer-made.` };
  }
  return { verdict: 'Inconclusive', confidence: 0.4, kind: 'unclear',
    reason: `The Commons record for ${info.name} shows no camera data and no sign of how it was made, so nothing settles it either way.` };
}

function shape(verdict, reason, confidence, extra) {
  const answer = `${verdict}. ${reason}`;
  return {
    status: 'ok', verdict, answer, summary: answer, reason, found: true, confidence,
    ...extra, checked_at: new Date().toISOString(),
  };
}

// Returns a full response body, or null when the question is not one of the
// settled cases (or the lookup failed) so the LLM judge should answer.
export async function lookupMedia(text, { fetchImpl = fetch } = {}) {
  const urls = findUrls(text);
  if (!urls.length) return null;

  for (const url of urls) {
    const name = commonsFileName(url);
    if (!name) continue;
    const info = await fetchRecord(name, fetchImpl);
    if (info === undefined) return null; // API trouble: let the judge answer
    const page = `https://commons.wikimedia.org/wiki/File:${encodeURIComponent(name.replace(/ /g, '_'))}`;
    if (info.missing) {
      return shape('Inconclusive',
        `No Wikimedia Commons file record exists for "${name}", so there are no bytes, hash or upload declaration to check; no evidence either way.`,
        0.2, { method: 'Looked the file name up on the Wikimedia Commons API; no such file.', source: page, canonical: `media-forensic:commons:${name}` });
    }
    const c = classifyRecord(info);
    return shape(c.verdict, c.reason, c.confidence, {
      method: 'Read the Wikimedia Commons file record (SHA-1, size, uploader, upload date, licence, camera data, categories) and decided from it.',
      sha1: info.sha1, size_bytes: info.size, mime: info.mime, uploader: info.uploader,
      uploaded_at: info.uploaded, license: info.license || null, camera: info.camera, artist: info.artist || null,
      source: page, canonical: `media-forensic:commons:${info.sha1}`,
    });
  }

  for (const url of urls) {
    let host;
    try { host = new URL(url).hostname; } catch { continue; }
    if (isPlaceholderHost(host)) {
      return shape('Inconclusive',
        `${host} is a reserved placeholder domain (RFC 2606), no real media file exists there, so nothing can be examined; no evidence either way.`,
        0.2, { method: 'Checked the host against the reserved example domains (RFC 2606); no file to fetch.', source: url, canonical: `media-forensic:placeholder:${url}` });
    }
  }
  return null;
}
